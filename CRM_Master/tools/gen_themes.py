assert light.keys() == dark.keys()
def write(name, pal):
    lines = ['<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"',
             '                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">',
             f'    <!-- {name} theme (generated by tools/gen_themes.py - edit the palette there) -->']
    for k, v in pal.items():
        lines.append(f'    <Color x:Key="Color.{k}">{v}</Color>')
        lines.append(f'    <SolidColorBrush x:Key="Brush.{k}" Color="{v}"/>')
    lines.append('</ResourceDictionary>')
    out = os.path.join(os.path.dirname(__file__), '..', 'CRM_Master.App', 'Themes', f'{name}.xaml')
    open(out, 'w').write('\n'.join(lines) + '\n')
write('Light', light); write('Dark', dark)
print('themes written:', len(light), 'colours each')

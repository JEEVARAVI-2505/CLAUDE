"""Assemble HTML and render PDF.  Run:  python3 build.py"""
import os, subprocess, sys
from lib import *
import sec_a as A, sec_b as B, sec_c as C

OUT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SECS = [
 ("sum", "", "Executive summary", A.exec_summary(), None),
 ("intake", "1", "Company intake (First task)", A.intake(), "Gate 0"),
 ("lifecycle", "2", "Lifecycle and 11 approval gates", A.lifecycle(), None),
 ("p1", "3", "Phase 1 - Market research & validation", A.phase1(), "Gate 1"),
 ("p2", "4", "Phase 2 - Requirements & I/O freeze", A.phase2(), "Gate 2"),
 ("p3", "5", "Phase 3 - Technology & architecture", A.phase3(), "Gate 3"),
 ("p4", "6", "Phase 4 - UI/UX & prototype", A.phase4(), "Gate 4"),
 ("p5", "7", "Phase 5 - Environment & repository", A.phase5(), "Gate 5"),
 ("p6", "8", "Phase 6 - Development", A.phase6(), "Gate 6"),
 ("p7", "9", "Phase 7 - QA & security", A.phase7(), "Gate 7"),
 ("p8", "10", "Phase 8 - Cost calculation (worked example: SiteDiary)", B.phase8() + B.infra_sim() + B.models(), "Gate 8"),
 ("p9", "11", "Phase 9 - Pricing, profit & break-even", B.phase9(), "Gate 8"),
 ("p10", "12", "Phase 10 - Build & app-store publishing", C.release(), "Gate 10"),
 ("p11", "13", "Phase 11 - Domain, DNS & deployment", C.deploy(), "Gate 9"),
 ("p12", "14", "Phase 12 - Showcase & sales", C.sales(), "Gate 11"),
 ("p13", "15", "Phase 13 - Maintenance & support", C.maintenance(), None),
 ("p14", "16", "Phase 14 - Employee management system", C.people(), None),
 ("p15", "17", "Phase 15 - Internal project portal", C.portal(), None),
 ("p16", "18", "Phase 16 - Sources & verification log", C.sources(), None),
 ("app", "19", "Appendix", C.appendix(), None),
]

def page(print_mode=False):
    toc = "".join(f'<a href="#{i}">{(n + ". ") if n else ""}{t}</a>' for i, n, t, _, _ in SECS)
    body = A.cover() + "".join(section(i, n or "★", t, b, g) for i, n, t, b, g in SECS)
    return f"""<!doctype html><html lang="en"{' class="print"' if print_mode else ''}><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Mobile App Company Operating System</title><style>{CSS}</style></head><body>
<button id="menu">Contents</button><nav id="toc"><div class="brand">Mobile App Company OS</div><div class="sub">v1.0 · 3 Nov 2026</div>{toc}</nav>
<main>{body}<footer>Planning figures are not quotations. Verify all provider prices and legal/tax positions before use. · Generated by build/build.py from model.py.</footer></main>
<script>{JS}</script></body></html>"""

if __name__ == "__main__":
    html = os.path.join(OUT, "Mobile-App-Company-OS.html")
    open(html, "w", encoding="utf-8").write(page())
    pr = os.path.join(OUT, "build", "_print.html")
    open(pr, "w", encoding="utf-8").write(page(True))
    js = """const {chromium}=require('playwright');(async()=>{const b=await chromium.launch();const p=await b.newPage();
await p.goto('file://'+process.argv[2]);await p.emulateMedia({media:'print'});
await p.pdf({path:process.argv[3],format:'A4',printBackground:true,margin:{top:'16mm',bottom:'16mm',left:'14mm',right:'14mm'},displayHeaderFooter:true,
headerTemplate:'<div></div>',footerTemplate:'<div style="font-size:8px;width:100%;text-align:center;color:#666">Mobile App Company Operating System v1.0 &nbsp;·&nbsp; <span class=pageNumber></span>/<span class=totalPages></span></div>'});await b.close()})()"""
    jp = os.path.join(OUT, "build", "_pdf.js"); open(jp, "w").write(js)
    subprocess.check_call(["node", jp, pr, os.path.join(OUT, "Mobile-App-Company-OS.pdf")])
    os.remove(pr); os.remove(jp)
    print("built")
